"""Per-project Node-RED containers (M5.2, D13/D10).

The portal is the spawner; Docker is reached only through the least-privilege socket proxy
(DOCKER_HOST=tcp://socket-proxy:2375). One instance per project: 0.5 CPU / 256 MB, its own named
volume, no host mounts, no published ports, attached to the `flows` network where only Caddy and
the portal can reach it. The editor is gated by Caddy forward_auth → /flows/auth (portal session).
A 30-minute idle culler stops instances; capacity assumption: ≤8 concurrent (see
CLAUDE.md)."""

